$apiKey = MAPY_CZ_API_KEY;

// Získej ID hry z URL
$gameId = $_GET['id'] ?? null;

if (!$gameId) {
    header('Location: dashboard.php');
    exit;
}

$pdo = getDB();

$gameStmt = $pdo->prepare("SELECT id, title, description, difficulty FROM games WHERE id = :id");
$gameStmt->execute(['id' => $gameId]);
$game = $gameStmt->fetch();

if (!$game) {
    header('Location: dashboard.php');
    exit;
}

$wpStmt = $pdo->prepare(
    "SELECT id, name, description, question, answer, lat, lng
     FROM waypoints WHERE game_id = :id ORDER BY order_index ASC"
);
$wpStmt->execute(['id' => $gameId]);
$waypoints = $wpStmt->fetchAll();

if (empty($waypoints)) {
    header('Location: dashboard.php');
    exit;
}

$progStmt = $pdo->prepare(
    "SELECT waypoints_completed FROM game_progress WHERE user_id = :uid AND game_id = :gid"
);
$progStmt->execute(['uid' => $_SESSION['user_id'], 'gid' => $gameId]);
$completedCount = (int)($progStmt->fetchColumn() ?: 0);

foreach ($waypoints as $index => &$wp) {
    $wp['lat'] = (float)$wp['lat'];
    $wp['lng'] = (float)$wp['lng'];
    $wp['completed'] = $index < $completedCount;
}
unset($wp);

$game['waypoints'] = $waypoints;

// Připočítej odehrání hry
$pdo->prepare("UPDATE games SET play_count = play_count + 1 WHERE id = :id")->execute(['id' => $gameId]);

